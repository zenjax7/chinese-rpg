#!/usr/bin/env python3
"""Global word bank for the editor and the editor API (level-editor.md §2.5.1): docs/data/curriculum/curriculum.csv ->
src/shared/level/wordbank.json as [id, simplified, traditional, pinyin, english] rows. Pinyin is data only (never shown in the game).
Run: python3 tools/editor/build_wordbank.py   (tests/api/levels.test.ts checks the file is in sync with the CSV)."""
import csv, json, os
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
rows = [[r['id'], r['simplified'], r['traditional'], r['pinyin'], r['english']]
        for r in csv.DictReader(open(os.path.join(ROOT, 'docs/data/curriculum/curriculum.csv'), encoding='utf-8-sig')) if r.get('id')]
out = os.path.join(ROOT, 'src/shared/level/wordbank.json')
with open(out, 'w', encoding='utf-8') as f:
    f.write('{"_note": "Generated by tools/editor/build_wordbank.py from docs/data/curriculum/curriculum.csv. Do not edit by hand.",\n "words": [\n')
    f.write(',\n'.join('  ' + json.dumps(r, ensure_ascii=False) for r in rows))
    f.write('\n]}\n')
print(f'wordbank: {len(rows)} words -> {os.path.relpath(out, ROOT)}')
