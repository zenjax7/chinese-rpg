#!/usr/bin/env python3
"""The version hash (level-editor.md §2.9) of every map bundled from docs/data/levels -> src/data/world/level-hashes.json.
The game compares it with the published index and fetches a map from the API only when they differ (src/world/levels.ts).
Same canonical JSON as src/shared/level/hash.ts (sorted keys, no whitespace, `version` left out); tests/api/levels.test.ts
checks the two agree on every map. Run: python3 tools/editor/level_hashes.py (npm run build runs it)."""
import glob, hashlib, json, os
ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
def js_numbers(v):
    """JSON.parse drops '.0' (9.0 -> 9), so integral floats hash as ints, like the browser and the server."""
    if isinstance(v, float) and v.is_integer(): return int(v)
    if isinstance(v, list): return [js_numbers(x) for x in v]
    if isinstance(v, dict): return {k: js_numbers(x) for k, x in v.items()}
    return v

out = {}
for p in sorted(glob.glob(os.path.join(ROOT, 'docs/data/levels/*.json'))):
    if os.path.basename(p) in ('index.json', 'world_rules.json'): continue
    d = js_numbers(json.load(open(p, encoding='utf-8'))); d.pop('version', None)
    out[d['id']] = hashlib.sha256(json.dumps(d, sort_keys=True, separators=(',', ':'), ensure_ascii=False).encode('utf-8')).hexdigest()
dst = os.path.join(ROOT, 'src/data/world/level-hashes.json')
with open(dst, 'w', encoding='utf-8') as f:
    json.dump({'_note': 'Generated by tools/editor/level_hashes.py from docs/data/levels. Do not edit by hand.', 'hashes': out}, f, indent=0, sort_keys=True)
    f.write('\n')
print(f'level hashes: {len(out)} maps -> {os.path.relpath(dst, ROOT)}')
