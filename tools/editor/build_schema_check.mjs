#!/usr/bin/env node
// Precompiles Desy's level/0.2 schema (docs/data/levels/schemas/level.schema.json) into a standalone ajv validator module:
// src/shared/level/schema-check.js. The site's CSP has no 'unsafe-eval', so ajv must not compile schemas in the browser
// (it builds code with new Function). Run by prebuild; tests/api/level-validate.test.ts fails if the output is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { Ajv2020 } from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
export function schemaCheckSource() {
  const schema = JSON.parse(readFileSync(join(ROOT, 'docs/data/levels/schemas/level.schema.json'), 'utf8'));
  const ajv = new Ajv2020({ allErrors: true, strict: false, code: { source: true, esm: true } });
  const code = standaloneCode.default ? standaloneCode.default(ajv, ajv.compile(schema)) : standaloneCode(ajv, ajv.compile(schema));
  // ajv's esm output still uses require() for its deep-equal helper; import fast-deep-equal (what that helper is) instead
  const esm = code.replace(/require\("ajv\/dist\/runtime\/equal"\)\.default/g, 'fastDeepEqual');
  if (/require\(/.test(esm)) throw new Error('standalone schema check still has a require()');
  return `// GENERATED by tools/editor/build_schema_check.mjs from docs/data/levels/schemas/level.schema.json. Do not edit.\n// eslint-disable\nimport fastDeepEqual from 'fast-deep-equal';\n${esm}\n`;
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const out = join(ROOT, 'src/shared/level/schema-check.js');
  writeFileSync(out, schemaCheckSource());
  console.log('schema check -> src/shared/level/schema-check.js');
}
